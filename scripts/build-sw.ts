/**
 * After `vite build`: write dist/sw.js, a service worker that precaches every file of this build
 * so the game installs and plays offline. The cache name carries a hash of the file list and
 * contents, so each deploy replaces the previous cache.
 */
import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const dist = new URL('../dist/', import.meta.url).pathname;

function walk(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const p = join(dir, name);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

// .woff duplicates the .woff2 fonts for very old browsers that cannot run a service worker anyway.
const files = walk(dist)
  .map((p) => relative(dist, p).split('\\').join('/'))
  // The share image is for link previews, never shown in the game: not worth an offline copy.
  .filter((f) => f !== 'sw.js' && !f.endsWith('.woff') && !f.endsWith('.map') && !f.startsWith('og-image'))
  .sort();

const hash = createHash('sha256');
for (const f of files) hash.update(f).update(readFileSync(join(dist, f)));
const version = hash.digest('hex').slice(0, 12);
const precache = ['./', ...files.filter((f) => f !== 'index.html')];

const sw = `/* Generated by scripts/build-sw.ts. Do not edit. */
const CACHE = 'paper-garden-${version}';
const PRECACHE = ${JSON.stringify(precache)};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    // Earlier versions' caches. Only this game's: on a shared origin (a project page on a host's
    // domain) other sites' caches are not ours to delete.
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('paper-garden-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

// Offline: the very file, if this version has it (the licence texts); below the site's root, the
// root (the page's relative links would point into that folder); else the game's page.
// Files are looked up in this version's cache only, never in another cache on the origin.
const mine = (req) => caches.open(CACHE).then((c) => c.match(req, { ignoreVary: true }));

async function offline(req) {
  const hit = await mine(req);
  if (hit) return hit;
  const scope = new URL(self.registration.scope);
  const rest = new URL(req.url).pathname.slice(scope.pathname.length);
  if (rest.includes('/')) return Response.redirect(scope.href, 302);
  return (await mine('./')) || Response.error();
}

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  if (req.mode === 'navigate') {
    // The page: network first, so a new version shows up at once. Nothing is written to the cache
    // here: each version's page is cached by its own worker at install, together with the files it
    // refers to, so an offline launch is always one whole version. (Caching what the network
    // returned once stored a licence text as the game, and a newer page without its files.)
    event.respondWith(fetch(req).catch(() => offline(req)));
    return;
  }
  // Hashed assets never change: cache first. Module scripts and fonts are CORS requests that carry
  // an Origin header, and servers may answer with "Vary: Origin"; match on the URL alone.
  event.respondWith(mine(req).then((hit) => hit || fetch(req)));
});
`;
writeFileSync(join(dist, 'sw.js'), sw);
console.log(`sw.js: cache paper-garden-${version}, ${precache.length} entries`);
